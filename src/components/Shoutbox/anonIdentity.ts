// Детерминированный псевдо-ник анона из anon_key (hash IP+соль+окно, приходит
// с бэка). Один анон в пределах окна — одно и то же животное и цвет; между
// окнами ключ меняется, трекинга нет. В v2 окно выросло с суток до недели, так
// что «Anon Otter» успевает стать узнаваемым собеседником, а не мелькнуть на
// вечер. Спека: wiki/components/shoutbox-v2-spec.md §7.

const ANIMALS = [
  'Fox', 'Crow', 'Owl', 'Lynx', 'Wolf', 'Hare', 'Bat', 'Toad', 'Moth', 'Stag',
  'Bear', 'Mole', 'Wren', 'Pike', 'Newt', 'Swan', 'Crab', 'Dove', 'Seal', 'Elk',
  'Vole', 'Kite', 'Carp', 'Finch', 'Otter', 'Ibis', 'Gecko', 'Heron', 'Shrew', 'Stoat',
];

// Приглушённые, но различимые на тёмном фоне.
// Красного здесь нет намеренно: красный ник в чате означает ровно одно —
// модератор. Остальные цвета равноправны и служат узнаванию, а не рангу.
// Розовый брать можно — с красным модератора его не путают, слишком разные.
//
// Восемнадцать, а не «побольше»: цвета раздаются по хешу, и в комнате из пяти
// человек двое всё равно иногда совпадут (парадокс дней рождения), а вот
// добавлять оттенки, которые глаз не отличает друг от друга, — терять то самое
// узнавание, ради которого всё и затевалось. Раздача по хешу ровная, проверено:
// на 140 тысячах случайных id перекос между цветами не больше 1.3%.
const COLORS = [
  '#f06292', '#ba68c8', '#9575cd', '#7986cb', '#64b5f6', '#90caf9',
  '#4fc3f7', '#4dd0e1', '#4db6ac', '#80cbc4', '#81c784', '#aed581', '#dce775',
  '#ffd54f', '#ffb74d', '#ff8a65', '#a1887f', '#b0bec5',
];

function djb2(s: string): number {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return h;
}

// nickColor — цвет ника по любому стабильному ключу. Анонимам достаётся по
// anon_key, зарегистрированным — по id записи. Именно по id, а не по нику: имя
// человек может сменить, и цвет, за который его в чате узнают, не должен от
// этого прыгать.
//
// Тема на сайте одна, тёмная, поэтому палитра тоже одна и подобрана под тёмный
// фон. Появится светлая — цвета придётся считать от неё, а не подкручивать эти.
export function nickColor(seed: string): string {
  return COLORS[Math.floor(djb2(seed || '?') / 31) % COLORS.length];
}

export function anonIdentity(anonKey: string): { name: string; color: string } {
  const h = djb2(anonKey || '?');
  return {
    name: `Anon ${ANIMALS[h % ANIMALS.length]}`,
    color: nickColor(anonKey),
  };
}
